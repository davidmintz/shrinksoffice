    public function findActive(): Array
    {
        return $this->createQueryBuilder('p')
            ->andWhere('p.active = 1')
            ->orderBy('p.lastname', 'ASC')
            ->orderBy('p.firstname', 'ASC')
            ->getQuery()
            ->getResult();
